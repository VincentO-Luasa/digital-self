"""``questions.md``: the knowledge gaps the brain wants to ask about (docs/vault-schema.md).

One list item per gap, open items first, highest priority first (the core card shows the first
open ones as "To ask"):

    - [ ] Where does Atlas Migration stand right now? (region:: projects)
      (about:: [[projects/atlas-migration]]) (slot:: status) (reason:: stale, noted 2026-08-01)
      (priority:: 5) (origin:: coverage) ^q-k2m4pa

(one line in the file; wrapped here).

Two kinds of items:

- **coverage** items (``origin:: coverage``) are rebuilt from the coverage report after every
  session: deterministic, at most ``MAX_PER_REGION`` per region. A gap that got filled
  disappears; ticking one (``[x]``) dismisses it for as long as the gap stays.
- **added** items come from other components (``add_question``: lint, graph cleaning, chat) or
  from the owner's hand edits (a line without ``origin::`` becomes ``origin:: owner``). They are
  kept across regenerations; an interview that asks one ticks it (``resolve_question``).

Fields: ``region``, ``about`` (entity wikilink), ``slot``, ``reason``, ``priority`` (1–5, 5 =
ask first), ``origin``, ``privacy`` (``private`` for private regions or entities: never shown
to the big model). Values never contain parentheses.
"""

from __future__ import annotations

import hashlib
import re
import sqlite3
from collections.abc import Iterable
from dataclasses import dataclass, replace
from datetime import date

from brain.interview.coverage import CoverageReport, SlotCoverage, coverage_report
from brain.vault import gitops
from brain.vault.store import Vault

HEADER = "# Questions"
NOTE = (
    "<!-- generated by brain: items with origin:: coverage are rebuilt after every session; "
    "other items are kept. Tick [x] to dismiss or close an item. -->"
)
COVERAGE = "coverage"
OWNER = "owner"
MAX_PER_REGION = 6
NEED = {"empty": 1.0, "stale": 0.8, "partial": 0.6, "discover": 1.0, "unplaced": 0.7}
FIELDS = ("region", "about", "slot", "reason", "priority", "origin", "privacy")

_ITEM = re.compile(r"^\s*[-*]\s+(?:\[( |x|X)\]\s+)?(.*?)\s*$")
_BLOCK = re.compile(r"\s*\^(q-[a-z0-9]+)$")
_FIELD = re.compile(r"\s*\((\w+)::\s*([^()]*?)\s*\)$")
_LINK = re.compile(r"^\[\[([^\]|]+)(?:\|[^\]]*)?\]\]$")
_B32 = "abcdefghijklmnopqrstuvwxyz234567"


def stable_id(key: str) -> str:
    digest = hashlib.sha1(key.encode()).digest()
    return "q-" + "".join(_B32[b % 32] for b in digest[:6])


def _clean(value: str) -> str:
    return " ".join(value.replace("(", "").replace(")", "").split())


@dataclass(frozen=True)
class GapItem:
    text: str
    region: str | None = None
    reason: str = ""
    priority: int = 3
    origin: str = OWNER
    about: str | None = None  # entity id
    slot: str | None = None
    private: bool = False
    done: bool = False
    qid: str = ""  # block id; derived from the item's key when empty

    @property
    def key(self) -> str:
        if self.origin == COVERAGE:
            parts = [self.region or "", self.slot or "", self.about or ""]
            return "coverage/" + "/".join(p for p in parts if p)
        return f"{self.origin}/{self.region or ''}/{' '.join(self.text.casefold().split())}"

    @property
    def id(self) -> str:
        return self.qid or stable_id(self.key)

    @property
    def open(self) -> bool:
        return not self.done

    def render(self) -> str:
        fields = {
            "region": self.region,
            "about": f"[[{self.about}]]" if self.about else None,
            "slot": self.slot,
            "reason": _clean(self.reason) or None,
            "priority": str(self.priority),
            "origin": self.origin,
            "privacy": "private" if self.private else None,
        }
        tail = "".join(f" ({k}:: {v})" for k, v in fields.items() if v)
        box = "x" if self.done else " "
        return f"- [{box}] {' '.join(self.text.split())}{tail} ^{self.id}"


# --- from coverage -----------------------------------------------------------------------------


def priority_for(weight: float, need: float) -> int:
    return max(1, min(5, int(5 * weight * need + 0.5)))


def _slot_item(s: SlotCoverage, weight: float, private: bool) -> GapItem:
    if s.status == "stale":
        fact = s.facts[0]
        text = f"{fact.text.rstrip('.')}: still true?"
        reason = f"stale, noted {fact.confirmed.isoformat()}"
    elif s.status == "partial":
        text = s.ask
        reason = f"partial, {round(s.score * s.needed)} of {s.needed}"
    else:
        text = s.ask
        reason = "empty"
    return GapItem(
        text=text,
        region=s.region,
        reason=reason,
        priority=priority_for(weight, NEED[s.status]),
        origin=COVERAGE,
        about=s.entity,
        slot=s.slot.id,
        private=private,
    )


DISCOVER = {
    "projects": "Which projects are you working on at the moment?",
    "relationships.family": "Who are the people in your family you're closest to?",
    "relationships.friends": "Who are the friends you see most?",
    "relationships.work": "Who do you work with most closely?",
}
DISCOVER_BY_TYPE = {
    "person": "Who are the people in your {label} I should know about?",
    "project": "Which projects should I know about?",
}


def discover_hint(region_id: str, label: str, entity_type: str | None, *, more: bool) -> str:
    """The question that finds entities for a per-entity region."""
    if more:
        if entity_type == "project":
            return "Are you working on any other projects I should know about?"
        if entity_type == "person":
            return f"Is there anyone else among your {label.casefold()} I should know about?"
        return f"Is there anything else about your {label.casefold()} I should know?"
    if region_id in DISCOVER:
        return DISCOVER[region_id]
    template = DISCOVER_BY_TYPE.get(entity_type or "", "What should I know about your {label}?")
    return template.format(label=label.casefold())


def gap_items(report: CoverageReport) -> list[GapItem]:
    """Coverage gaps as questions.md items (deterministic)."""
    out: list[GapItem] = []
    for region in report.regions.values():
        weight = region.region.weight
        label = region.region.label or region.id
        items: list[GapItem] = []
        if region.per_entity and not region.entities:
            items.append(
                GapItem(
                    text=discover_hint(region.id, label, region.per_entity, more=False),
                    region=region.id,
                    reason="none known yet",
                    priority=priority_for(weight, NEED["discover"]),
                    origin=COVERAGE,
                    slot="discover",
                    private=region.private,
                )
            )
        private_entities = {e.id for e in region.entities if e.private}
        for s in region.gaps:
            items.append(_slot_item(s, weight, region.private or s.entity in private_entities))
        items.sort(key=lambda i: -i.priority)  # stable: slot and entity order otherwise
        out.extend(items[:MAX_PER_REGION])
    for e in report.unplaced:
        out.append(
            GapItem(
                text=f"Who is {e.name} to you?",
                region=None,
                reason="relation unknown",
                priority=priority_for(0.6, NEED["unplaced"]),
                origin=COVERAGE,
                about=e.id,
                slot="relation",
                private=e.private,
            )
        )
    return out


# --- file --------------------------------------------------------------------------------------


def parse_questions(text: str) -> list[GapItem]:
    items = []
    for line in text.splitlines():
        m = _ITEM.match(line)
        if not m or not m.group(2):
            continue
        body = m.group(2)
        qid = ""
        if b := _BLOCK.search(body):
            qid, body = b.group(1), body[: b.start()]
        fields: dict[str, str] = {}
        while f := _FIELD.search(body):
            fields.setdefault(f.group(1), f.group(2))
            body = body[: f.start()]
        body = body.strip()
        if not body:
            continue
        about = fields.get("about")
        if about and (link := _LINK.match(about)):
            about = link.group(1).strip()
        try:
            priority = max(1, min(5, int(fields.get("priority", "3"))))
        except ValueError:
            priority = 3
        items.append(
            GapItem(
                text=body,
                region=fields.get("region") or None,
                reason=fields.get("reason", ""),
                priority=priority,
                origin=fields.get("origin") or OWNER,
                about=about or None,
                slot=fields.get("slot") or None,
                private=fields.get("privacy") == "private",
                done=(m.group(1) or " ") != " ",
                qid=qid,
            )
        )
    return items


def _order(items: Iterable[GapItem], region_order: dict[str | None, int]) -> list[GapItem]:
    def key(i: GapItem) -> tuple:
        return (i.done, -i.priority, region_order.get(i.region, len(region_order)), i.key)

    return sorted(items, key=key)


def render_questions(items: Iterable[GapItem], region_order: dict[str | None, int]) -> str:
    lines = [HEADER, "", NOTE, ""]
    lines += [i.render() for i in _order(items, region_order)]
    return "\n".join(lines).rstrip() + "\n"


def merge(existing: Iterable[GapItem], generated: Iterable[GapItem]) -> list[GapItem]:
    """Added items kept; coverage items replaced by ``generated`` (a dismissed one stays
    dismissed while its gap remains)."""
    existing = list(existing)
    dismissed = {i.id for i in existing if i.origin == COVERAGE and i.done}
    kept = [i for i in existing if i.origin != COVERAGE]
    out: dict[str, GapItem] = {}
    for item in kept:
        out.setdefault(item.id, item)
    for item in generated:
        out.setdefault(item.id, replace(item, done=item.id in dismissed))
    return list(out.values())


def read_questions(vault: Vault) -> list[GapItem]:
    path = vault.questions_path
    return parse_questions(path.read_text(encoding="utf-8")) if path.exists() else []


def _region_order(vault: Vault) -> dict[str | None, int]:
    return {rid: n for n, rid in enumerate(vault.lifemap.regions)}


def _write(vault: Vault, items: Iterable[GapItem]) -> bool:
    text = render_questions(items, _region_order(vault))
    path = vault.questions_path
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    tmp = path.with_name(f".{path.name}.tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(path)
    return True


def _commit(vault: Vault, message: str) -> None:
    gitops.commit_all(vault.root, message)


def write_questions(vault: Vault, report: CoverageReport) -> bool:
    """Rebuild the coverage items of questions.md; True if the file changed."""
    return _write(vault, merge(read_questions(vault), gap_items(report)))


def refresh_questions(
    vault: Vault, db: sqlite3.Connection, *, today: date | None = None, commit: bool = True
) -> bool:
    """Coverage from the index, then questions.md (committed when it changed)."""
    changed = write_questions(vault, coverage_report(db, vault.lifemap, today))
    if changed and commit:
        _commit(vault, "brain: regenerate questions.md")
    return changed


def add_question(
    vault: Vault,
    text: str,
    *,
    region: str | None = None,
    reason: str = "",
    priority: int = 3,
    origin: str = "brain",
    about: str | None = None,
    private: bool | None = None,
    commit: bool = False,
) -> GapItem:
    """Add a question for a later interview (idempotent: the same text and region from the same
    origin is one item). ``private`` defaults to the region's privacy in the life map."""
    if origin == COVERAGE:
        raise ValueError("coverage items are generated; use another origin")
    if private is None:
        private = bool(region) and vault.lifemap.privacy_for([region or ""]) == "private"
    item = GapItem(
        text=" ".join(text.split()),
        region=region,
        reason=reason,
        priority=max(1, min(5, priority)),
        origin=_clean(origin) or "brain",
        about=about,
        private=private,
    )
    items = read_questions(vault)
    if all(i.id != item.id for i in items):
        items.append(item)
        if _write(vault, items) and commit:
            _commit(vault, f"brain: question {item.id}")
    return next(i for i in read_questions(vault) if i.id == item.id)


def resolve_question(vault: Vault, qid: str, *, commit: bool = False) -> bool:
    """Tick an item (asked and answered); True if it was open."""
    items = read_questions(vault)
    if not any(i.id == qid and i.open for i in items):
        return False
    _write(vault, [replace(i, done=True) if i.id == qid else i for i in items])
    if commit:
        _commit(vault, f"brain: question {qid} answered")
    return True
